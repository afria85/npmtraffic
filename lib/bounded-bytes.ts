export class ByteLimitError extends Error {
  constructor() {
    super("Payload exceeds the byte limit.");
  }
}

export async function readBoundedBytes(stream: ReadableStream<Uint8Array>, limit: number) {
  const reader = stream.getReader();
  const chunks: Uint8Array[] = [];
  let size = 0;
  try {
    for (;;) {
      const { value, done } = await reader.read();
      if (done) break;
      size += value.byteLength;
      if (size > limit) {
        // A slow underlying cancel must not delay rejection of an oversized body.
        void reader.cancel().catch(() => {});
        throw new ByteLimitError();
      }
      chunks.push(value);
    }
  } finally {
    reader.releaseLock();
  }
  const output = new Uint8Array(size);
  let offset = 0;
  for (const chunk of chunks) {
    output.set(chunk, offset);
    offset += chunk.byteLength;
  }
  return output;
}
